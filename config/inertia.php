        'ensure_pages_exist' => true,

        'paths' => [
            resource_path('ts/Pages'),
        ],

        'extensions' => [
            'svelte',
        ],

    ],

    /*
    |--------------------------------------------------------------------------
    | SSR
    |--------------------------------------------------------------------------
    |
    | サーバーサイドレンダリングは使わない。全画面がログイン必須の社内ツールで
    | SEO が要らず、常時 Node のプロセスを動かす構成を避けたいため。
    |
    */

    'ssr' => [
        'enabled' => false,
    ],

